function merge(target, source) {
  let added = 0
  for (const [k, v] of Object.entries(source)) {
    if (typeof v === 'object' && v !== null) {
      target[k] ??= {}
      added += merge(target[k], v)
    } else if (!(k in target)) {
      target[k] = v
      added++
    }
  }
  return added
}

for (const lng of ['es', 'en']) {
  const file = join(locales, lng, 'common.json')
  const json = JSON.parse(readFileSync(file, 'utf8'))
  const added = merge(json, seed[lng])
  writeFileSync(file, JSON.stringify(json, null, 2) + '\n', 'utf8')
  console.log(`${lng}: +${added} keys`)
}

// parity check
const es = JSON.parse(readFileSync(join(locales, 'es', 'common.json'), 'utf8'))
const en = JSON.parse(readFileSync(join(locales, 'en', 'common.json'), 'utf8'))
const flat = (o, p = '') =>
  Object.entries(o).flatMap(([k, v]) =>
    typeof v === 'object' && v !== null ? flat(v, `${p}${k}.`) : [`${p}${k}`],
  )
const a = new Set(flat(es))
const b = new Set(flat(en))
const missingEn = [...a].filter((k) => !b.has(k))
const missingEs = [...b].filter((k) => !a.has(k))
console.log(`keys es=${a.size} en=${b.size}`)
if (missingEn.length || missingEs.length) {
  console.log('missing in en:', missingEn)
  console.log('missing in es:', missingEs)
  process.exit(1)
}
console.log('parity OK')
